6. האם ציינת את הכבישים הראשיים הרלוונטיים?
7. האם התייחסת לפיתוח ולתשתיות?
8. האם הטקסט תמציתי ומתאים לשומת מקרקעין?
9. האם נמנעת ממידע שיווקי או מהבעת דעה שאינה שמאית?
10. האם כל העובדות מבוססות ולא הומצאו?
